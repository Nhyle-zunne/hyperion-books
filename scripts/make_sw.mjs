import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, readdirSync, } from 'node:fs';
import { join, relative } from 'node:path';

const root = process.argv[2] || 'build/web';
if (!existsSync(join(root, 'index.html'))) throw new Error('Flutter web build missing index.html');
// Works with stable Flutter releases even when --web-content-hash is unavailable.
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(item => {
    const file = join(dir, item.name);
    if (item.isDirectory()) return walk(file);
    if (!item.isFile()) return [];
    const name = relative(root, file).replaceAll('\\', '/');
    if (/\.map$/.test(name) || ['sw.js','flutter_service_worker.js','_headers',
      'precache_manifest.json'].includes(name)) return [];
    return [name];
  });
}
const files = walk(root).sort();
for (const required of ['index.html','flutter_bootstrap.js','manifest.json']) {
  if (!files.includes(required)) throw new Error(`Missing app shell: ${required}`);
}
const hash = createHash('sha256');
for (const file of files) {
  hash.update(file);
  hash.update(readFileSync(join(root,file)));
}
const cacheVersion = hash.digest('hex').slice(0, 12);
const code = `/* Generated by scripts/make_sw.mjs */
const CACHE = 'hyperion-books-shell-${cacheVersion}';
const OFFLINE_FILES = ${JSON.stringify(files.map(x => './' + x))};
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  await cache.addAll(OFFLINE_FILES);
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) {
    if (key.startsWith('hyperion-books-shell-') && key !== CACHE) await caches.delete(key);
  }
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try { const response = await fetch(request); if (response.ok) return response; }
      catch (_) {}
      return (await caches.match('./index.html')) || Response.error();
    })());
    return;
  }
  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try { return await fetch(request); }
    catch (_) { return Response.error(); }
  })());
});
`;
writeFileSync(join(root, 'sw.js'), code);
console.log(`Generated offline shell ${cacheVersion} with ${files.length} assets`);
