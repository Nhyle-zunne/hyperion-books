import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2] || 'build/web';
const manifestPath = join(root, 'precache_manifest.json');
if (!existsSync(manifestPath)) throw new Error('Build with flutter build web --web-content-hash first.');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
if (!Array.isArray(manifest.entries) || manifest.entries.length === 0) {
  throw new Error('Flutter precache manifest has no entries');
}
const files = [...new Set(['index.html','manifest.json','favicon.png','icons/Icon-192.png',
  ...manifest.entries.map(e => e.url).filter(Boolean)])].filter(x => !x.endsWith('.map') && x !== 'sw.js');
for (const file of files) {
  if (!existsSync(join(root, file))) throw new Error(`Missing offline asset: ${file}`);
}
const hash = createHash('sha256').update(JSON.stringify(manifest.entries)).digest('hex').slice(0, 12);
const code = `/* Generated by scripts/make_sw.mjs; do not edit */
const CACHE = 'hyperion-books-shell-${hash}';
const OFFLINE_FILES = ${JSON.stringify(files.map(x => './'+x))};
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  // Fail installation rather than claim offline support with a partial shell.
  await cache.addAll(OFFLINE_FILES);
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) {
    if (key.startsWith('hyperion-books-shell-') && key !== CACHE) await caches.delete(key);
  }
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  const url = new URL(request.url);
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) return response;
      } catch (_) {}
      return (await caches.match('./index.html')) || Response.error();
    })());
    return;
  }
  event.respondWith((async () => {
    const saved = await caches.match(request);
    if (saved) return saved;
    try { return await fetch(request); }
    catch (_) { return Response.error(); }
  })());
});
`;
writeFileSync(join(root, 'sw.js'), code);
console.log(`Generated offline shell ${hash} with ${files.length} assets`);
